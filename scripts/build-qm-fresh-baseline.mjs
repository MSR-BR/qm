// Deterministic fresh-only baseline. Historical migration files are never edited.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
const root = new URL('../', import.meta.url);
const target = 'supabase/fresh/supabase/migrations/20260926204825_qm_clean_baseline.sql';
const receipt = 'supabase/fresh/baseline-manifest.json';
const sha = value => createHash('sha256').update(value).digest('hex');
const files = readdirSync(new URL('supabase/migrations/',root)).filter(f=>f.endsWith('.sql')).sort();
assert.equal(files.length,21,'Baseline source set changed; review before regenerating');
let guarded = 0;
const sources = [];
const chunks = files.map(file=>{
  const path = 'supabase/migrations/'+file;
  const original = readFileSync(new URL(path,root),'utf8');
  let sql = original.replace(/^(begin|commit);\s*$/gmi,'');
  if(file==='20260910230457_qm_operational_parity.sql') {
    const unsafe = 'revoke execute on function public.rls_auto_enable() from public;';
    assert.equal(sql.split(unsafe).length,2);
    sql=sql.replace(unsafe,`-- Optional managed helper: absent on some fresh Supabase instances.
do $qm_optional_helper$ begin
  if to_regprocedure('public.rls_auto_enable()') is not null then
    execute 'revoke execute on function public.rls_auto_enable() from public';
  end if;
end $qm_optional_helper$;`);
    guarded++;
  }
  sources.push({path,sha256:sha(original)});
  return '-- SOURCE: '+path+'\n'+sql.trim();
});
assert.equal(guarded,1);
const sql=`-- GENERATED by scripts/build-qm-fresh-baseline.mjs; do not edit by hand.
-- Fresh QUANTUM only. Not an upgrade or repair of an existing database.
-- The migration runner must execute this file and its history entry atomically.
do $qm_empty_destination$ begin
  if exists (select 1 from pg_tables where schemaname in ('public','private') and tablename like 'qm_%') then
    raise exception 'Fresh QUANTUM baseline refuses an existing application schema';
  end if;
end $qm_empty_destination$;
\n${chunks.join('\n\n')}\n`;
const manifest={format:'qm-fresh-baseline-v1',projectRef:'crasnnvdvujzxudmbakv',migration:target,
  migrationVersion:'20260926204825',sha256:sha(sql),sources,
  transformations:['Strip standalone outer BEGIN/COMMIT so the runner owns the atomic transaction',
    'Guard optional public.rls_auto_enable() revoke in 20260910230457 only'],
  authorization:'Fresh empty QUANTUM replacement; no TERMO, no historical data import, no app cutover'};
if(process.argv[2]==='--write') {
  // Mechanical generated artifacts, not hand-authored source edits.
  writeFileSync(new URL(target,root),sql);
  writeFileSync(new URL(receipt,root),JSON.stringify(manifest,null,2)+'\n');
} else {
  assert.equal(readFileSync(new URL(target,root),'utf8'),sql,'Generated SQL is stale');
  assert.deepEqual(JSON.parse(readFileSync(new URL(receipt,root),'utf8')),manifest,'Manifest is stale');
}
console.log(JSON.stringify({ok:true,migration:target,sha256:manifest.sha256,sources:sources.length}));
