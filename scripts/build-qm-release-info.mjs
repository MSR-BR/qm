import path from "node:path";
import { fileURLToPath } from "node:url";
import { writeFile } from "node:fs/promises";

const __filename = fileURLToPath(import.meta.url);
const rootDir = path.resolve(path.dirname(__filename), "..");
const outputPath = path.join(rootDir, "assets", "qm-release.js");
const now = new Date();
const date = now.toISOString().slice(0, 10);
const label = new Intl.DateTimeFormat("en-GB", { timeZone: "America/Sao_Paulo", day: "2-digit", month: "2-digit", year: "numeric" }).format(now);
const version = `v${date.replaceAll("-", "")}.${String(now.getUTCHours()).padStart(2, "0")}${String(now.getUTCMinutes()).padStart(2, "0")}`;
const source = `/* Generated by scripts/build-qm-release-info.mjs. Do not edit manually. */\nwindow.QMReleaseInfo = Object.freeze(${JSON.stringify({ version, date, label }, null, 2)});\n`;
await writeFile(outputPath, source, "utf8");
console.log(`Release metadata generated: ${version} (${label})`);
